"""Regenerate one static page per tag under tags/<slug>.md.

GitHub Pages builds this site with vanilla Jekyll (no custom plugins), so
per-tag pages can't be generated by a Jekyll generator at build time. This
script scans _posts/*.md front matter for tags and writes/updates one file
per tag so pages/tags.html's links (/tags/<slug>/) resolve instead of 404ing.

Run it after adding or changing tags on any post:
    python scripts/generate_tag_pages.py
"""
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
POSTS_DIR = REPO_ROOT / "_posts"
TAGS_DIR = REPO_ROOT / "tags"


def slugify(tag: str) -> str:
    """Mirror Jekyll's default `slugify` filter."""
    return re.sub(r"[^a-z0-9]+", "-", tag.lower()).strip("-")


def extract_tags(post_text: str) -> list[str]:
    match = re.search(r"^tags:\s*\[(.*?)\]\s*$", post_text, re.MULTILINE)
    if not match:
        return []
    raw = match.group(1)
    return [t.strip() for t in raw.split(",") if t.strip()]


def main() -> None:
    all_tags: dict[str, str] = {}
    for post_path in POSTS_DIR.glob("*.md"):
        text = post_path.read_text(encoding="utf-8")
        for tag in extract_tags(text):
            all_tags[slugify(tag)] = tag

    TAGS_DIR.mkdir(exist_ok=True)

    existing_slugs = {p.stem for p in TAGS_DIR.glob("*.md")}
    generated_slugs = set()

    for slug, tag_name in sorted(all_tags.items()):
        generated_slugs.add(slug)
        tag_file = TAGS_DIR / f"{slug}.md"
        tag_file.write_text(
            "---\n"
            "layout: tag\n"
            f"title: \"{tag_name}\"\n"
            f"tag: \"{tag_name}\"\n"
            f"permalink: /tags/{slug}/\n"
            "---\n",
            encoding="utf-8",
        )

    stale = existing_slugs - generated_slugs
    for slug in stale:
        (TAGS_DIR / f"{slug}.md").unlink()

    print(f"Wrote {len(generated_slugs)} tag page(s) to {TAGS_DIR}")
    if stale:
        print(f"Removed {len(stale)} stale tag page(s): {sorted(stale)}")


if __name__ == "__main__":
    main()
